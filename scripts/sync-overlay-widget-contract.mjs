#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
// Portable files shared by the API (canonical) and Overlay Studio (generated copies).
const pairs = [
  ['../dimabot/src/overlays/widget-contract.ts', '../dimasite/src/app/features/overlays/overlay-widget-contract.generated.ts'],
  ['../dimabot/src/custom_widgets/format.ts', '../dimasite/src/app/features/overlays/custom-widget-format.generated.ts']
];
for (const [from, to] of pairs) {
  const source = new URL(from, import.meta.url), target = new URL(to, import.meta.url);
  const expected = '// Generated by scripts/sync-overlay-widget-contract.mjs. Do not edit.\n' + await readFile(source, 'utf8');
  if (process.argv.includes('--check')) {
    const current = await readFile(target, 'utf8').catch(() => '');
    if (current !== expected) { console.error(`${to.split('/').pop()} is stale; run node scripts/sync-overlay-widget-contract.mjs`); process.exitCode = 1; }
  } else await writeFile(target, expected);
}
