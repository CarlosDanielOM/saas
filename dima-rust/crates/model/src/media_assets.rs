//! `mediaassets`: an uploaded media file (video, audio, image, GIF) in S3, owned by a channel or
//! shared publicly, with its reference counters and generated thumbnail.
//!
//! Reference: `dimabot/src/schemas/media_asset.schema.ts` (model `MediaAsset`), written by
//! `server/routes/trigger.route.ts` (`Model.create` on upload, `doc.save()` when an asset is made
//! public, `$set`/`$inc` of the counters), `utils/thumbnail_generator.ts` (the thumbnail asset's
//! `create`, `$set`/`$inc` of the thumbnail state) and `utils/media_cleanup.ts`. Camel-case
//! timestamps, `__v`, no hooks. Indexes: eight field-level ones, the unique `s3Key` (one record
//! per stored object; best effort like the reference, which awaits nothing) and the
//! marketplace scan.
//!
//! Legacy shapes accepted: 18 documents from before `alertReferenceCount` and
//! `extensionReferenceCount`, 17 from before the thumbnail fields (read with the defaults); the
//! `default: null` paths are stored as `null` (`legacyTriggerFileID`, `proxyPath`,
//! `checksumSha256`, `thumbnailAssetID`, `thumbnailLastError`, `deletedAt`).
//!
//! Client-fed writes (`null` from a request body): none. `server/routes/trigger.route.ts` stores
//! upload metadata the server derived (`req.file`, S3 keys, counts).
//!
//! Intended difference (`crate::shape`): the write helpers refuse a value of the wrong BSON type,
//! and `null` or a removal where [`READ_NEEDS`] says the read type has none; the census of the
//! production copy shows none stored there, so Mongoose's acceptance of them is not reproduced.

