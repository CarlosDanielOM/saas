#!/usr/bin/env node
// Portable files shared by the API (canonical, dimabot) and the site (generated copies, dimasite). Edit only the API
// file, then run `node scripts/sync-overlay-widget-contract.mjs`. `--check` fails when a copy is stale (saas-ops runs it
// before building api, bot, cron and site). A shared file may only import other shared files: the copy's imports are
// rewritten to the generated names, and any other relative import is refused (it would not exist on the site).
import { readFile, writeFile } from 'node:fs/promises';
import { posix } from 'node:path';

const root = new URL('..', import.meta.url);
const SITE = 'dimasite/src/app/features/overlays';
const FILES = [
  ['dimabot/src/overlays/widget-contract.ts', `${SITE}/overlay-widget-contract.generated.ts`],
  ['dimabot/src/custom_widgets/format.ts', `${SITE}/custom-widget-format.generated.ts`],
  ['dimabot/src/overlays/keyframes.ts', `${SITE}/overlay-keyframes.generated.ts`],
  ['dimabot/src/overlays/model.ts', `${SITE}/overlay-model.generated.ts`],
  ['dimabot/src/overlays/library.ts', `${SITE}/overlay-library.generated.ts`],
  ['dimabot/src/overlays/protocol.ts', `${SITE}/overlay-protocol.generated.ts`]
];
const HEADER = '// Generated by scripts/sync-overlay-widget-contract.mjs. Do not edit.\n';
const copies = new Map(FILES);
const SPECIFIER = /(\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)(['"])(\.{1,2}\/[^'"]+)\2/g;

/** The copy for `to`: header plus the source with relative imports pointing at the other generated copies. */
function generated(from, to, source) {
  return HEADER + source.replace(SPECIFIER, (_match, lead, quote, specifier) => {
    const target = posix.normalize(posix.join(posix.dirname(from), specifier.replace(/\.js$/, '.ts')));
    const copy = copies.get(target);
    if (!copy) throw new Error(`${from} imports ${specifier}, which is not a shared file; shared files may only import each other`);
    let path = posix.relative(posix.dirname(to), copy).replace(/\.ts$/, '');
    if (!path.startsWith('.')) path = './' + path;
    return `${lead}${quote}${path}${quote}`;
  });
}

let stale = 0;
for (const [from, to] of FILES) {
  const expected = generated(from, to, await readFile(new URL(from, root), 'utf8'));
  if (process.argv.includes('--check')) {
    const current = await readFile(new URL(to, root), 'utf8').catch(() => '');
    if (current !== expected) { stale++; console.error(`${to} is stale; run node scripts/sync-overlay-widget-contract.mjs`); }
  } else await writeFile(new URL(to, root), expected);
}
if (stale) process.exitCode = 1;
else if (process.argv.includes('--check')) console.log(`Shared overlay files are in sync (${FILES.length}).`);
