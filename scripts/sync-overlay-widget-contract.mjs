#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
const source = new URL('../dimabot/src/overlays/widget-contract.ts', import.meta.url);
const target = new URL('../dimasite/src/app/features/overlays/overlay-widget-contract.generated.ts', import.meta.url);
const expected = '// Generated by scripts/sync-overlay-widget-contract.mjs. Do not edit.\n' + await readFile(source, 'utf8');
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== expected) { console.error('Overlay widget contract is stale; run node scripts/sync-overlay-widget-contract.mjs'); process.exitCode = 1; }
} else await writeFile(target, expected);
