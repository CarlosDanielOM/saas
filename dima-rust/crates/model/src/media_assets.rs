/// A stored media asset.
#[derive(Clone, Debug, Deserialize)]
pub struct MediaAsset {
    /// `_id`.
    #[serde(rename = "_id")]
    pub id: ObjectId,
    /// The trigger file it was migrated from.
    #[serde(default, rename = "legacyTriggerFileID")]
    pub legacy_trigger_file_id: Option<ObjectId>,
    /// The owning user.
    #[serde(rename = "ownerUserID")]
    pub owner_user_id: String,
    /// The owning channel.
    #[serde(rename = "ownerChannelID")]
    pub owner_channel_id: String,
    /// The owning channel's login.
    #[serde(rename = "ownerChannelName")]
    pub owner_channel_name: String,
    /// Who uploaded it.
    #[serde(rename = "uploadedByUserID")]
    pub uploaded_by_user_id: String,
    /// The uploaded file's name.
    #[serde(rename = "originalName")]
    pub original_name: String,
    /// Display name.
    #[serde(rename = "displayName")]
    pub display_name: String,
    /// The stored file's name.
    #[serde(rename = "fileName")]
    pub file_name: String,
    /// Extension.
    pub extension: String,
    /// MIME type.
    #[serde(rename = "mimeType")]
    pub mime_type: String,
    /// Media type.
    #[serde(rename = "mediaType")]
    pub media_type: Open<MediaType>,
    /// Size in bytes.
    pub bytes: JsNumber,
    /// S3 bucket.
    pub bucket: String,
    /// S3 key (unique).
    #[serde(rename = "s3Key")]
    pub s3_key: String,
    /// Public URL.
    #[serde(rename = "storageUrl")]
    pub storage_url: String,
    /// Proxy path.
    #[serde(default, rename = "proxyPath")]
    pub proxy_path: Option<String>,
    /// Who may use it.
    pub scope: Open<AssetScope>,
    /// Marketplace status.
    #[serde(default = "not_listed", rename = "marketplaceStatus")]
    pub marketplace_status: Open<MarketplaceStatus>,
    /// SHA-256 of the file (never computed so far).
    #[serde(default, rename = "checksumSha256")]
    pub checksum_sha256: Option<String>,
    /// The generated thumbnail asset.
    #[serde(default, rename = "thumbnailAssetID")]
    pub thumbnail_asset_id: Option<ObjectId>,
    /// Thumbnail state.
    #[serde(default = "pending", rename = "thumbnailStatus")]
    pub thumbnail_status: Open<ThumbnailStatus>,
    /// Thumbnail attempts.
    #[serde(default = "zero", rename = "thumbnailAttempts")]
    pub thumbnail_attempts: JsNumber,
    /// The last thumbnail failure.
    #[serde(default, rename = "thumbnailLastError")]
    pub thumbnail_last_error: Option<String>,
    /// Libraries holding it.
    #[serde(default = "zero", rename = "libraryCount")]
    pub library_count: JsNumber,
    /// Triggers using it.
    #[serde(default = "zero", rename = "triggerReferenceCount")]
    pub trigger_reference_count: JsNumber,
    /// Alerts using it.
    #[serde(default = "zero", rename = "alertReferenceCount")]
    pub alert_reference_count: JsNumber,
    /// Extension items using it.
    #[serde(default = "zero", rename = "extensionReferenceCount")]
    pub extension_reference_count: JsNumber,
    /// When it was deleted.
    #[serde(default, rename = "deletedAt")]
    pub deleted_at: Option<JsDate>,
    /// Creation time.
    #[serde(default, rename = "createdAt")]
    pub created_at: Option<JsDate>,
    /// Last update time.
    #[serde(default, rename = "updatedAt")]
    pub updated_at: Option<JsDate>,
}

fn not_listed() -> Open<MarketplaceStatus> {
    Open::Known(MarketplaceStatus::NotListed)
}

fn pending() -> Open<ThumbnailStatus> {
    Open::Known(ThumbnailStatus::Pending)
}

