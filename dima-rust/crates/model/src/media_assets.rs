/// The collection name.
pub const COLLECTION: &str = "mediaassets";

str_enum! {
    /// `scope`.
    pub enum AssetScope {
        /// In the public library.
        Public = "public",
        /// The owner's only.
        Private = "private",
        /// Generated by the system (thumbnails).
        System = "system",
    }
}

str_enum! {
    /// `marketplaceStatus`.
    pub enum MarketplaceStatus {
        /// Not listed (the default).
        NotListed = "not_listed",
        /// Published.
        Published = "published",
        /// Waiting for review.
        PendingReview = "pending_review",
        /// Hidden.
        Hidden = "hidden",
        /// Removed.
        Removed = "removed",
    }
}

str_enum! {
    /// `thumbnailStatus`.
    pub enum ThumbnailStatus {
        /// To generate (the default).
        Pending = "pending",
        /// Generated.
        Ready = "ready",
        /// Generation failed.
        Failed = "failed",
        /// Not generated (audio).
        Skipped = "skipped",
    }
}

