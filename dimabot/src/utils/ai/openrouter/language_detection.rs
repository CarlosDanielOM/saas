const PATTERNS: [(&str, &[&str]); 4] = [
    ("english", ENGLISH),
    ("spanish", SPANISH),
    ("portuguese", PORTUGUESE),
    ("french", FRENCH),
];
#[derive(Default)]
pub struct LanguageDetector {
    last_match: [bool; 4],
}
fn word(unit: u16) -> bool {
    letter(unit) || (u16::from(b'0')..=u16::from(b'9')).contains(&unit) || unit == u16::from(b'_')
}
fn letter(unit: u16) -> bool {
    (u16::from(b'a')..=u16::from(b'z')).contains(&unit)
        || (u16::from(b'A')..=u16::from(b'Z')).contains(&unit)
}
impl LanguageDetector {
    pub fn detect(&mut self, text: &JsString, threshold: f64) -> &'static str {
        let lower = js_unicode::lowercase(text);
        let units = lower.units();
        let mut words = Vec::new();
        let mut i = 0;
        while i < units.len() {
            if !letter(units[i]) {
                i += 1;
                continue;
            }
            let start = i;
            while i < units.len() && letter(units[i]) {
                i += 1
            }
            if (start == 0 || !word(units[start - 1])) && (i == units.len() || !word(units[i])) {
                words.push(String::from_utf16(&units[start..i]).expect("ASCII"));
            }
        }
        if words.is_empty() {
            return "unknown";
        }
        let mut best = "unknown";
        let mut score = 0.0;
        for (index, (name, pattern)) in PATTERNS.iter().enumerate() {
            let mut matches = 0usize;
            for word in &words {
                if self.last_match[index] {
                    self.last_match[index] = false;
                    continue;
                }
                if pattern.contains(&word.as_str()) {
                    matches += 1;
                    self.last_match[index] = true;
                }
            }
            let ratio = matches as f64 / words.len() as f64;
            if ratio > score && ratio >= threshold {
                score = ratio;
                best = name
            }
        }
        best
    }
}
/// Source module-level global RegExp state, shared across calls.
pub fn detect_language(text: &JsString, threshold: Option<f64>) -> &'static str {
    static DEFAULT: OnceLock<Mutex<LanguageDetector>> = OnceLock::new();
    DEFAULT
        .get_or_init(|| Mutex::new(LanguageDetector::default()))
        .lock()
        .unwrap_or_else(|e| e.into_inner())
        .detect(text, threshold.unwrap_or(0.1))
}
