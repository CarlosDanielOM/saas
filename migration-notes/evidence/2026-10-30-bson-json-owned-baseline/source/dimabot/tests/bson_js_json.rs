#![cfg(feature = "bson-js-json")]
use dima_rust::utils::bson_js_json::bson_js_json;
use mongodb::bson::{Bson, DateTime, Document, doc};

#[test]
fn ordinary_values_and_undefined_contexts() {
    let v = Bson::Document(doc! {
        "date": DateTime::from_millis(0), "large": 9_007_199_254_740_993_i64,
        "omitted": Bson::Undefined, "array": [Bson::Undefined, Bson::Int32(2)],
        "nonfinite": f64::INFINITY,
    });
    assert_eq!(
        bson_js_json(&v).unwrap().to_json_string(),
        r#"{"date":"1970-01-01T00:00:00.000Z","large":{"low":1,"high":2097152,"unsigned":false},"array":[null,2],"nonfinite":null}"#
    );
    assert!(bson_js_json(&Bson::Undefined).is_err());
}

#[test]
fn dbpointer_and_complex_regexp_projection() {
    // BSON DBPointer namespace "a.bc" and ObjectId 00112233445566778899aabb.
    let bytes: [u8; 29] = [
        29, 0, 0, 0, 12, b'p', 0, 5, 0, 0, 0, b'a', b'.', b'b', b'c', 0, 0, 17, 34, 51, 68, 85,
        102, 119, 136, 153, 170, 187, 0,
    ];
    let doc = Document::from_reader(bytes.as_slice()).unwrap();
    assert_eq!(
        bson_js_json(&Bson::Document(doc)).unwrap().to_json_string(),
        r#"{"p":{"$ref":"bc","$id":"00112233445566778899aabb","$db":"a"}}"#
    );
    let re = mongodb::bson::Regex {
        pattern: "a+".try_into().unwrap(),
        options: "i".try_into().unwrap(),
    };
    assert_eq!(
        bson_js_json(&Bson::RegularExpression(re))
            .unwrap()
            .to_json_string(),
        "{}"
    );
}

#[test]
fn dbref_plain_prototype_is_not_an_own_json_field() {
    let ref_doc = doc! {"$ref":"db.collection", "$id":"id", "__proto__": {"p": 1}, "tail":"value"};
    assert_eq!(
        bson_js_json(&Bson::Document(ref_doc))
            .unwrap()
            .to_json_string(),
        r#"{"$ref":"collection","$id":"id","tail":"value","$db":"db"}"#
    );
}

#[test]
fn dbref_prototype_setters_and_readonly_assignments_follow_order() {
    use mongodb::bson::oid::ObjectId;
    let oid = ObjectId::parse_str("00112233445566778899aabb").unwrap();
    let safe = Bson::Document(
        doc! {"$ref":"c", "$id":"id", "_bsontype":"before", "__proto__":oid, "tail":1},
    );
    assert_eq!(
        bson_js_json(&safe).unwrap().to_json_string(),
        r#"{"$ref":"c","$id":"id","_bsontype":"before","tail":1}"#
    );
    let rejected =
        Bson::Document(doc! {"$ref":"c", "$id":"id", "__proto__":oid, "_bsontype":"after"});
    assert!(bson_js_json(&rejected).is_err());
    let setter =
        Bson::Document(doc! {"$ref":"c", "$id":"id", "__proto__":oid, "id":"new", "tail":1});
    assert_eq!(
        bson_js_json(&setter).unwrap().to_json_string(),
        r#"{"$ref":"c","$id":"id","buffer":"new","tail":1}"#
    );
}

/// The external fixture is generated by the pinned real SDK in an isolated
/// environment. The caller supplies a separately captured digest; integration
/// must freeze it in the repository's evidence after running --write/--check.
#[test]
#[ignore = "requires external pinned Node SDK oracle and independently recorded fixture SHA-256"]
fn replay_pinned_driver_bson_bytes() {
    use sha2::{Digest, Sha256};
    let path = std::env::var("DIMA_BSON_JSON_FIXTURE").expect("absolute external fixture path");
    assert!(std::path::Path::new(&path).is_absolute());
    let bytes = std::fs::read(&path).unwrap();
    let actual = format!("{:x}", Sha256::digest(&bytes));
    let expected_hash = std::env::var("DIMA_BSON_JSON_FIXTURE_SHA256")
        .expect("recorded independent fixture digest");
    assert_eq!(actual, expected_hash);
    let fixture: serde_json::Value = serde_json::from_slice(&bytes).unwrap();
    assert_eq!(
        fixture["nodeSha"],
        "569128f3066ac7be59b10b9a0adef708def642ee37cbf9d560a9bdb68f872108"
    );
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let hashes = fixture["sourceHashes"].as_object().unwrap();
    for (name, expected) in hashes {
        let name = if name == "oracle" {
            "tests/fixtures/bson_js_json_reference.cjs"
        } else {
            name
        };
        let digest = format!(
            "{:x}",
            Sha256::digest(std::fs::read(root.join(name)).unwrap())
        );
        assert_eq!(digest, expected.as_str().unwrap(), "source pin: {name}");
    }
    for case in fixture["records"].as_array().unwrap() {
        let name = case["name"].as_str().unwrap();
        let hex = case["hex"].as_str().unwrap().as_bytes();
        assert_eq!(hex.len() % 2, 0);
        let raw: Vec<u8> = hex
            .as_chunks::<2>()
            .0
            .iter()
            .map(|pair| u8::from_str_radix(std::str::from_utf8(pair).unwrap(), 16).unwrap())
            .collect();
        let doc = Document::from_reader(raw.as_slice())
            .unwrap_or_else(|e| panic!("{name}: native BSON decode: {e}"));
        let projected = bson_js_json(&Bson::Document(doc));
        if !case["error"].is_null() {
            if name == "regex-invalid-reader" {
                // Reader-only RegExp validation is outside projection scope.
            } else {
                assert!(
                    name.starts_with("readonly-after-"),
                    "unexpected SDK decode error: {name}"
                );
                assert_eq!(case["error"].as_str(), Some("TypeError"));
                assert!(projected.is_err(), "{name}: Object.assign must fail");
            }
        } else if case["unsupported"].as_bool().unwrap() {
            assert!(
                projected.is_err(),
                "{name}: unsupported projection must fail explicitly"
            );
        } else {
            assert_eq!(
                projected
                    .unwrap_or_else(|e| panic!("{name}: {e}"))
                    .to_json_string(),
                case["expected"].as_str().unwrap(),
                "{name}"
            );
        }
    }
}
